function comparison = runSingleTrackSlipComparisonV2(performanceMap, options)
%RUNSINGLETRACKSLIPCOMPARISONV2 Compare direct and slip V2 single track.
%   Pass an existing map with BuildMap=false, or [] with BuildMap=true.
%   Both cases retain identical vehicle, aero and solver limits.
arguments
    performanceMap = []
    options.BuildMap (1,1) logical = true
end
%% Shared vehicle and track
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(root,fullfile(root,'vehicles'),fullfile(root,'config')); 
vehicle=FAUmaxTauV2("fourMotorAWD"); tracks=lts.io.trackCatalog();
track=lts.io.loadTrackMatrix(tracks.endurance,true);
assert(isempty(performanceMap)==options.BuildMap,'lts:v2:MapSelection', ...
    'Build a map or supply one, but not both.');
%% Select or build the explicit performance map
if options.BuildMap, performanceMap=lts.model.singleTrackSlip.buildPerformanceMap(vehicle); end
tl=lts.v2.trackLocalSettings(SpeedRows=3,LateralFractions=[], ...
    BoundaryIterations=6,InterpolationSafetyFactor=NaN,ShowProgress=false,AuditPointCount=8);
configs={ ...
    lts.v2.explicitCase(Vehicle=vehicle,Track=track,Model="singleTrack", ...
        Aero=true,LoadTransfer=true,TireSlip=false,Energy=false,YawInertia=false, ...
        ChassisTorsion=false,Strategy="direct",MaximumSpeed_mps=100, ...
        InitialSpeed_mps=0,FinalSpeed_mps=Inf,PerformanceMap=[],TrackLocal=tl), ...
    lts.v2.explicitCase(Vehicle=vehicle,Track=track,Model="singleTrack", ...
        Aero=true,LoadTransfer=true,TireSlip=true,Energy=false,YawInertia=false, ...
        ChassisTorsion=false,Strategy="mapped",MaximumSpeed_mps=100, ...
        InitialSpeed_mps=0,FinalSpeed_mps=Inf,PerformanceMap=performanceMap,TrackLocal=tl)};
%% Run direct and mapped cases
comparison=struct('model',{},'lapTime_s',{},'result',{});
for k=1:2
    result=lts.v2.runCase(configs{k}); comparison(k)=struct( ...
        'model',result.meta.modelFamily,'lapTime_s',result.lap.lapTime_s,'result',result);
end
end
