function comparison = runRollStiffnessSlipComparison()
%RUNROLLSTIFFNESSSLIPCOMPARISON Compare roll distributions with Level 2.1c.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot, fullfile(projectRoot, 'vehicles'));
resultDirectory = fullfile(projectRoot, 'results');
baselineFile = fullfile(resultDirectory, 'slipModelComparison.mat');
assert(isfile(baselineFile), 'lts:runner:MissingBaselineMap', ...
    'Run runSlipModelComparison before the roll-stiffness slip comparison.');
baselineData = load(baselineFile, 'performanceMap');
baselineMap = baselineData.performanceMap;
baselineVehicle = FAUmaxTauV2("fourMotorAWD");
[derivedVehicle, rollProperties] = ...
    lts.suspension.applyRollStiffness(baselineVehicle);
derivedMap = lts.model.dualTrackSlip.buildPerformanceMap(derivedVehicle, ...
    speedGrid_mps=baselineMap.speedGrid_mps, ...
    lateralFractions=baselineMap.lateralFractions, ...
    boundaryIterations=baselineMap.meta.boundaryIterations, ...
    interpolationSafetyFactor=baselineMap.meta.interpolationSafetyFactor);
trackFiles = lts.io.trackCatalog();
trackFile = trackFiles.endurance;
track = lts.io.loadTrackMatrix(trackFile, true);
vehicles = {baselineVehicle, derivedVehicle};
maps = {baselineMap, derivedMap};
names = {'Slip map with fixed 50/50 roll moment', ...
    'Slip map with derived elastic roll stiffness'};
comparison = struct('name', {}, 'frontRollMomentFraction', {}, ...
    'lapTime_s', {}, 'result', {});
for index = 1:numel(vehicles)
    config = lts.config.createCase(Model="dualTrackSlipFitted", ...
        Vehicle=vehicles{index}, Strategy="mapped", ...
        PerformanceMap=maps{index}, IncludeEnergy=false, ...
        IncludeYawInertia=false, MaximumSpeed_mps=Inf, ...
        InitialSpeed_mps=0, FinalSpeed_mps=0);
    result = lts.design.runCase(config, track);
    comparison(index).name = names{index};
    comparison(index).frontRollMomentFraction = ...
        vehicles{index}.suspension.frontRollMomentFraction;
    comparison(index).lapTime_s = result.lap.lapTime_s;
    comparison(index).result = result;
    fprintf('%-48s front=%6.3f  %9.3f s\n', names{index}, ...
        comparison(index).frontRollMomentFraction, result.lap.lapTime_s);
end
resultFile = fullfile(resultDirectory, 'rollStiffnessSlipComparison.mat');
assert(~isfile(resultFile), 'lts:io:ResultExists', ...
    'Result file already exists; refusing to overwrite: %s', resultFile);
save(resultFile, 'comparison', 'baselineMap', 'derivedMap', 'rollProperties');
end
