function report = runEnergyReport(caseConfig)
%RUNENERGYREPORT Simulate the baseline and print event energy targets.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot, fullfile(projectRoot, 'vehicles'), ...
    fullfile(projectRoot, 'config'));
assert(nargin == 1 && isstruct(caseConfig), ...
    'lts:energy:ExplicitConfigurationRequired', ...
    ['Pass an explicit configuration from sensitivityStudyCase or an ' ...
    'equivalent fully specified struct.']);

baselineParameter = caseConfig.parameters(1);
baselineParameter.values = baselineParameter.baseline;
caseConfig.parameters = baselineParameter;
study = runSensitivityStudy(caseConfig);
report.meta = study.meta;
report.vehicle = study.cases(1).vehicle;
report.events = study.cases(1).eventResults;

fprintf('\n%-24s %9s %9s %9s %9s\n', ...
    'Event', 'Time [s]', 'Net [kWh]', 'Reku [kWh]', 'Pack [kWh]');
for index = 1:numel(report.events)
    event = report.events(index);
    fprintf('%-24s %9.3f %9.3f %9.3f %9.3f\n', event.name, ...
        event.time_s, event.energy.netBatteryEnergy_kWh, ...
        event.energy.recoveredEnergy_kWh, ...
        event.energy.requiredInstalledCapacity_kWh);
end

enduranceIndex = find(strcmp({report.events.id}, 'endurance'), 1);
if ~isempty(enduranceIndex)
    energy = report.events(enduranceIndex).energy;
    report.accumulatorTarget = energy;
    fprintf('\nEndurance accumulator target\n');
    fprintf('Installed capacity: %.3f kWh / %.3f Ah at %.0f V\n', ...
        energy.requiredInstalledCapacity_kWh, ...
        energy.requiredNominalCapacity_Ah, ...
        report.vehicle.energy.nominalAccumulatorVoltage_V);
    fprintf('Estimated pack mass: %.2f kg\n', ...
        energy.estimatedAccumulatorMass_kg);
    fprintf('Reku potential used: %.1f %%\n', ...
        100 * energy.regenPotentialUtilization);
    fprintf('Peak discharge / charge: %.1f / %.1f kW\n', ...
        energy.peakBatteryDischargePower_kW, ...
        energy.peakBatteryChargePower_kW);
    fprintf('SoC start / finish: %.1f / %.1f %%\n', ...
        100 * energy.initialSoc, 100 * energy.finalSoc);
    fprintf('Discharge power target exceeded: %d\n', ...
        energy.exceedsBatteryDischargePowerLimit);
    fprintf('Power-limited segments: %d\n', ...
        energy.powerLimitedSegmentCount);
end
end
