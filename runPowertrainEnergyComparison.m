function comparison = runPowertrainEnergyComparison()
%RUNPOWERTRAINENERGYCOMPARISON Compare laptime, energy and regen by layout.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot, fullfile(projectRoot, 'vehicles'));
events = lts.config.events.fsg2026();
endurance = events(strcmp({events.id}, 'endurance'));
layoutNames = ["singleFrontMotor", "singleRearMotor", ...
    "dualFrontMotors", "dualRearMotors", "dualMotorAWD", "fourMotorAWD"];
comparison = struct('layout', {}, 'lapTime_s', {}, ...
    'netBatteryEnergy_kWh', {}, 'recoveredEnergy_kWh', {}, ...
    'regenPotentialUtilization', {}, ...
    'requiredInstalledCapacity_kWh', {}, ...
    'peakBatteryDischargePower_kW', {}, ...
    'peakBatteryChargePower_kW', {}, 'eventResult', {});

fprintf('%-24s %9s %9s %9s %9s\n', ...
    'Layout', 'Time [s]', 'Net [kWh]', 'Reku [kWh]', 'Pack [kWh]');
for index = 1:numel(layoutNames)
    vehicle = FAUmaxTauV2(layoutNames(index));
    model = lts.model.dualTrackEnvelope.create(vehicle);
    eventResult = lts.events.runSet(endurance, model, ...
        IncludeDriverless=false, CoupleEnergy=false);
    energy = eventResult.energy;
    comparison(index).layout = char(layoutNames(index));
    comparison(index).lapTime_s = eventResult.time_s;
    comparison(index).netBatteryEnergy_kWh = energy.netBatteryEnergy_kWh;
    comparison(index).recoveredEnergy_kWh = energy.recoveredEnergy_kWh;
    comparison(index).regenPotentialUtilization = ...
        energy.regenPotentialUtilization;
    comparison(index).requiredInstalledCapacity_kWh = ...
        energy.requiredInstalledCapacity_kWh;
    comparison(index).peakBatteryDischargePower_kW = ...
        energy.peakBatteryDischargePower_kW;
    comparison(index).peakBatteryChargePower_kW = ...
        energy.peakBatteryChargePower_kW;
    comparison(index).eventResult = eventResult;
    fprintf('%-24s %9.3f %9.3f %9.3f %9.3f\n', ...
        layoutNames(index), eventResult.time_s, ...
        energy.netBatteryEnergy_kWh, energy.recoveredEnergy_kWh, ...
        energy.requiredInstalledCapacity_kWh);
end

resultDirectory = fullfile(projectRoot, 'results');
if ~isfolder(resultDirectory)
    mkdir(resultDirectory);
end
resultFile = fullfile(resultDirectory, 'powertrainEnergyComparison.mat');
assert(~isfile(resultFile), 'lts:io:ResultExists', ...
    'Result file already exists; refusing to overwrite: %s', resultFile);
save(resultFile, 'comparison');
end
