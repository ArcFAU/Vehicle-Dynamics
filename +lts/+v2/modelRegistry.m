function models = modelRegistry(model)
%MODELREGISTRY The only public V2 model families.

models = struct( ...
    'id', {'pointMass', 'singleTrack', 'dualTrack'}, ...
    'description', { ...
        'Fast concept and sensitivity model', ...
        'Axle-resolved balance model', ...
        'Wheel-resolved vehicle-dynamics model'});
if nargin == 0
    return
end
model = string(model);
match = string({models.id}) == model;
assert(nnz(match) == 1, 'lts:v2:Model', ...
    'Model must be pointMass, singleTrack or dualTrack.');
models = models(match);
end
