function result = runCase(config)
%RUNCASE Validate, disclose and execute one transparent V2 case.

[config, report] = lts.v2.validateCase(config, Display=true);
legacy = lts.config.createCase(Vehicle=config.effectiveVehicle, ...
    Model=string(config.legacyModelId), ...
    Strategy=string(config.legacyStrategy), ...
    IncludeEnergy=config.features.energy, ...
    IncludeYawInertia=config.features.yawInertia, ...
    MaximumSpeed_mps=config.solver.maximumSpeed_mps, ...
    InitialSpeed_mps=config.solver.initialSpeed_mps, ...
    FinalSpeed_mps=config.solver.finalSpeed_mps, ...
    PerformanceMap=config.solver.performanceMap, ...
    TrackLocalSpeedRows=config.solver.trackLocal.speedRows, ...
    TrackLocalLateralFractions=config.solver.trackLocal.lateralFractions, ...
    TrackLocalBoundaryIterations=...
        config.solver.trackLocal.boundaryIterations, ...
    TrackLocalInterpolationSafetyFactor=...
        config.solver.trackLocal.interpolationSafetyFactor, ...
    TrackLocalShowProgress=config.solver.trackLocal.showProgress, ...
    TrackLocalAuditPointCount=config.solver.trackLocal.auditPointCount, ...
    ShowSummary=false);

result = lts.design.runCase(legacy, config.track);
result.meta.interface = 'transparent V2';
result.meta.modelFamily = config.model;
result.meta.features = config.features;
result.meta.effectiveConfiguration = config;
result.meta.inputReport = report.inputs;
end
