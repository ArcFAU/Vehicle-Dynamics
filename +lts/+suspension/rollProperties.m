function properties = rollProperties(vehicle)
%ROLLPROPERTIES Derive elastic axle roll stiffness and moment distribution.
% Motion ratio convention is wheel travel divided by damper travel.

lts.validation.validateVehicle(vehicle);
front = vehicle.suspension.front;
rear = vehicle.suspension.rear;
properties.frontWheelRate_Npm = front.springRate_Npm ...
    / front.motionRatioWheelPerDamper ^ 2;
properties.rearWheelRate_Npm = rear.springRate_Npm ...
    / rear.motionRatioWheelPerDamper ^ 2;
properties.frontAxleRollStiffness_NmPerRad = ...
    0.5 * properties.frontWheelRate_Npm ...
    * vehicle.geometry.frontTrack_m ^ 2 ...
    + front.antiRollStiffness_NmPerRad;
properties.rearAxleRollStiffness_NmPerRad = ...
    0.5 * properties.rearWheelRate_Npm ...
    * vehicle.geometry.rearTrack_m ^ 2 ...
    + rear.antiRollStiffness_NmPerRad;
properties.totalRollStiffness_NmPerRad = ...
    properties.frontAxleRollStiffness_NmPerRad ...
    + properties.rearAxleRollStiffness_NmPerRad;
assert(properties.totalRollStiffness_NmPerRad > 0, ...
    'lts:suspension:ZeroRollStiffness', ...
    'Total elastic roll stiffness must be positive.');
properties.frontRollMomentFraction = ...
    properties.frontAxleRollStiffness_NmPerRad ...
    / properties.totalRollStiffness_NmPerRad;
properties.rearRollMomentFraction = ...
    1 - properties.frontRollMomentFraction;
end
