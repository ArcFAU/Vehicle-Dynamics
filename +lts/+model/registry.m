function definition = registry(modelId)
%REGISTRY Return canonical model definitions and their factories.

definitions = [ ...
    entry("pointMass", "0.1", "direct", "none", "any", false, "none", ...
        @(vehicle, strategy, map) lts.model.pointMass.create(vehicle)), ...
    entry("pointMassLoadSensitive", "0.2", "direct", "none", "selected", ...
        false, "none", ...
        @(vehicle, strategy, map) ...
            lts.model.pointMassLoadSensitive.create(vehicle)), ...
    entry("pointMassAero", "0.3", ["direct", "legacyQss"], "none", ...
        "selected", false, "none", ...
        @createPointMassAero), ...
    entry("singleTrack", "1.1", "direct", "none", "selected", false, ...
        "none", ...
        @(vehicle, strategy, map) lts.model.singleTrack.create(vehicle)), ...
    entry("singleTrackAero", "1.2", ["direct", "legacyQss"], "none", ...
        "selected", false, "singleTrackAero", ...
        @createSingleTrackAero), ...
    entry("singleTrackSlip", "1.3", ["trackLocal", "mapped"], ...
        "singleTrack", "selected", true, "singleTrackSlip", ...
        @(vehicle, strategy, map) ...
            lts.model.singleTrackSlip.create(vehicle, map)), ...
    entry("dualTrackEnvelope", "2.0", "direct", "none", ...
        "selected", false, "none", ...
        @(vehicle, strategy, map) lts.model.dualTrackEnvelope.create(vehicle)), ...
    entry("dualTrackSlipFitted", "2.1", ["trackLocal", "mapped"], ...
        "dualTrack", "fittedCombinedSlip", true, "dualTrackSlip", ...
        @(vehicle, strategy, map) ...
            createDualTrackSlip(vehicle, map, "fittedCombinedSlip")), ...
    entry("dualTrackSlipTMeasy", "2.5", ["trackLocal", "mapped"], ...
        "dualTrack", "tmeasyAdtm", true, "dualTrackSlip", ...
        @(vehicle, strategy, map) ...
            createDualTrackSlip(vehicle, map, "tmeasyAdtm"))];

if nargin == 0
    definition = definitions;
    return
end
modelId = string(modelId);
matches = [definitions.id] == modelId;
assert(nnz(matches) == 1, 'lts:model:RegistryId', ...
    'Unknown or ambiguous model ID: %s.', modelId);
definition = definitions(matches);
end

function value = entry(id, level, strategies, mapType, tireRequirement, ...
    supportsYawAudit, operatingPointType, factory)
value.id = id;
value.level = level;
value.strategies = strategies;
value.mapType = mapType;
value.tireRequirement = tireRequirement;
value.supportsYawAudit = supportsYawAudit;
value.operatingPointType = operatingPointType;
value.factory = factory;
end

function model = createPointMassAero(vehicle, strategy, ~)
if strategy == "legacyQss"
    model = lts.model.pointMassAero.create(vehicle, UseAxleLoads=true);
    model.executionStrategy = 'legacyQss';
    model.name = 'Level 0.3 Legacy-compatible point mass';
else
    model = lts.model.pointMassAero.create(vehicle);
end
end

function model = createSingleTrackAero(vehicle, strategy, ~)
if strategy == "legacyQss"
    model = lts.model.singleTrackLegacyQss.create(vehicle);
else
    model = lts.model.singleTrackAero.create(vehicle);
end
end

function model = createDualTrackSlip(vehicle, map, requiredTireModel)
assert(string(vehicle.tireModel.active) == requiredTireModel, ...
    'lts:model:RegistryTireModel', ...
    'Model requires tire model "%s", but vehicle selects "%s".', ...
    requiredTireModel, vehicle.tireModel.active);
model = lts.model.dualTrackSlip.create(vehicle, map);
end
