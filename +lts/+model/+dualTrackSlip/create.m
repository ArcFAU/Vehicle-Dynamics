function model = create(vehicle, performanceMap)
%CREATE Build Level 2.1c lap model from slip-consistent boundaries.

lts.validation.validateVehicle(vehicle);
validateMap(performanceMap);
assert(isfield(performanceMap.meta, 'sourceVehicleDefinition'), ...
    'lts:model:MapMetadata', ...
    ['Performance map lacks its complete source vehicle definition. ' ...
    'Rebuild the map with the current software before using it.']);
assert(isequaln(performanceMap.meta.sourceVehicleDefinition, vehicle), ...
    'lts:model:MapConfiguration', ...
    ['Performance map belongs to a different vehicle definition. ' ...
    'Rebuild it after every physics-relevant vehicle change.']);
selectedTireModel = lts.tire.create(vehicle);
requiredIdentityFields = {'tireModel', 'tireParameterSet', ...
    'tireModelVersion', 'tireParameterVersion', ...
    'driveAllocationMode', 'brakeAllocationMode', 'targetYawMoment_Nm'};
for fieldIndex = 1:numel(requiredIdentityFields)
    assert(isfield(performanceMap.meta, requiredIdentityFields{fieldIndex}), ...
        'lts:model:MapMetadata', ...
        'Missing required performance-map metadata: %s.', ...
        requiredIdentityFields{fieldIndex});
end
mapTireModel = performanceMap.meta.tireModel;
mapParameterSet = performanceMap.meta.tireParameterSet;
mapModelVersion = performanceMap.meta.tireModelVersion;
mapParameterVersion = performanceMap.meta.tireParameterVersion;
assert(strcmp(mapTireModel, selectedTireModel.type) ...
    && strcmp(mapParameterSet, selectedTireModel.parameterSet) ...
    && strcmp(mapModelVersion, selectedTireModel.version) ...
    && strcmp(mapParameterVersion, selectedTireModel.parameterVersion), ...
    'lts:model:MapConfiguration', ...
    'Performance map tire model or parameter set does not match the vehicle.');
assert(strcmp(performanceMap.meta.powertrainLayout, ...
    vehicle.powertrain.layout), 'lts:model:MapConfiguration', ...
    'Performance map powertrain layout does not match the vehicle.');
mapDriveMode = performanceMap.meta.driveAllocationMode;
mapBrakeMode = performanceMap.meta.brakeAllocationMode;
mapTargetYawMoment_Nm = performanceMap.meta.targetYawMoment_Nm;
assert(strcmp(mapDriveMode, vehicle.controls.driveAllocation.mode) ...
    && strcmp(mapBrakeMode, vehicle.controls.brakeAllocation.mode) ...
    && isequal(mapTargetYawMoment_Nm, vehicle.controls.targetYawMoment_Nm), ...
    'lts:model:MapConfiguration', ...
    'Performance map control allocation does not match the vehicle.');
if isfield(performanceMap.meta, 'wheelActuatorGroups')
    assert(isequal(performanceMap.meta.wheelActuatorGroups, ...
        vehicle.powertrain.wheelActuatorGroups), ...
        'lts:model:MapConfiguration', ...
        'Performance map actuator groups do not match the vehicle.');
end
assert(isfield(performanceMap.meta, 'frontRollMomentFraction') ...
    && abs(performanceMap.meta.frontRollMomentFraction ...
    - vehicle.suspension.frontRollMomentFraction) < 1e-12, ...
    'lts:model:MapConfiguration', ...
    'Performance map roll distribution does not match the vehicle.');
assert(isfield(performanceMap.meta, 'chassisTorsionalStiffness_NmPerRad') ...
    && isequal(performanceMap.meta.chassisTorsionalStiffness_NmPerRad, ...
    vehicle.chassis.torsionalStiffness_NmPerRad), ...
    'lts:model:MapConfiguration', ...
    'Performance map chassis stiffness does not match the vehicle.');
model.name = sprintf('Slip-Consistent Dual Track - %s', ...
    selectedTireModel.type);
model.level = performanceMap.meta.modelLevel;
model.vehicle = vehicle;
model.performanceMap = performanceMap;
model.maximumSpeedForCurvature = @(curvature_1pm) ...
    maximumSpeedForCurvature(performanceMap, curvature_1pm);
model.accelerationLimits = @(speed_mps, lateralAcceleration_mps2) ...
    accelerationLimits(performanceMap, speed_mps, lateralAcceleration_mps2);
model.operatingPoint = @(speed_mps, longitudinalAcceleration_mps2, ...
    lateralAcceleration_mps2) lts.model.dualTrackSlip.operatingPoint(...
    vehicle, speed_mps, longitudinalAcceleration_mps2, ...
    lateralAcceleration_mps2);
end

function maximumSpeed_mps = maximumSpeedForCurvature(map, curvature_1pm)
validateattributes(curvature_1pm, {'numeric'}, {'real', 'finite'});
maximumSpeed_mps = zeros(size(curvature_1pm));
for index = 1:numel(curvature_1pm)
    if curvature_1pm(index) == 0
        maximumSpeed_mps(index) = map.speedGrid_mps(end);
        continue
    end
    directionIndex = directionFor(map, curvature_1pm(index));
    lowerSpeed_mps = 0;
    upperSpeed_mps = map.speedGrid_mps(end);
    for iteration = 1:40
        candidateSpeed_mps = (lowerSpeed_mps + upperSpeed_mps) / 2;
        lateralLimit_mps2 = interpolateLateralLimit(map, ...
            candidateSpeed_mps, directionIndex);
        required_mps2 = candidateSpeed_mps ^ 2 * abs(curvature_1pm(index));
        if required_mps2 <= lateralLimit_mps2
            lowerSpeed_mps = candidateSpeed_mps;
        else
            upperSpeed_mps = candidateSpeed_mps;
        end
    end
    maximumSpeed_mps(index) = lowerSpeed_mps;
end
end

function limits = accelerationLimits(map, speed_mps, lateralAcceleration_mps2)
validateattributes(speed_mps, {'numeric'}, {'real', 'finite', 'nonnegative'});
validateattributes(lateralAcceleration_mps2, {'numeric'}, ...
    {'real', 'finite', 'size', size(speed_mps)});
limits.maximumAcceleration_mps2 = zeros(size(speed_mps));
limits.maximumDeceleration_mps2 = zeros(size(speed_mps));
limits.feasible = false(size(speed_mps));
for index = 1:numel(speed_mps)
    directionIndex = directionFor(map, lateralAcceleration_mps2(index));
    lateralLimit_mps2 = interpolateLateralLimit(map, ...
        speed_mps(index), directionIndex);
    if lateralLimit_mps2 <= 0
        continue
    end
    fraction = abs(lateralAcceleration_mps2(index)) / lateralLimit_mps2;
    if fraction > 1 + 1e-12
        continue
    end
    fraction = min(fraction, 1);
    querySpeed_mps = min(max(speed_mps(index), map.speedGrid_mps(1)), ...
        map.speedGrid_mps(end));
    limits.maximumAcceleration_mps2(index) = interp2(...
        map.lateralFractions, map.speedGrid_mps, ...
        map.maximumAcceleration_mps2(:, :, directionIndex), ...
        fraction, querySpeed_mps, 'linear');
    limits.maximumDeceleration_mps2(index) = interp2(...
        map.lateralFractions, map.speedGrid_mps, ...
        map.maximumDeceleration_mps2(:, :, directionIndex), ...
        fraction, querySpeed_mps, 'linear');
    limits.feasible(index) = true;
end
end

function lateralLimit_mps2 = interpolateLateralLimit(map, speed_mps, directionIndex)
querySpeed_mps = min(max(speed_mps, map.speedGrid_mps(1)), ...
    map.speedGrid_mps(end));
lateralLimit_mps2 = interp1(map.speedGrid_mps, ...
    map.maximumLateralAcceleration_mps2(:, directionIndex), ...
    querySpeed_mps, 'linear');
end

function directionIndex = directionFor(map, signedValue)
if signedValue < 0
    directionIndex = find(map.turnDirections < 0, 1, 'first');
else
    directionIndex = find(map.turnDirections > 0, 1, 'first');
end
end

function validateMap(map)
requiredFields = {'meta', 'speedGrid_mps', 'lateralFractions', ...
    'turnDirections', 'maximumLateralAcceleration_mps2', ...
    'maximumAcceleration_mps2', 'maximumDeceleration_mps2'};
for index = 1:numel(requiredFields)
    assert(isfield(map, requiredFields{index}), 'lts:model:PerformanceMap', ...
        'Missing performance-map field %s.', requiredFields{index});
end
assert(numel(map.turnDirections) == 2 ...
    && any(map.turnDirections < 0) && any(map.turnDirections > 0), ...
    'lts:model:PerformanceMap', ...
        'Performance map requires negative and positive turn directions.');
end
