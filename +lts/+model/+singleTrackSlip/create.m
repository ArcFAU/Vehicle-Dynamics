function model = create(vehicle, performanceMap)
%CREATE Build fast Level 1.3 single-track slip model from a validated map.

expected = [vehicle.geometry.frontTrack_m, vehicle.geometry.rearTrack_m, ...
    vehicle.mass.total_kg, vehicle.geometry.wheelbase_m, ...
    vehicle.geometry.frontMassFraction, vehicle.geometry.cgHeight_m, ...
    vehicle.mass.yawInertia_kgm2];
fields = {'sourceVehicleFrontTrack_m', 'sourceVehicleRearTrack_m', ...
    'sourceVehicleMass_kg', 'sourceVehicleWheelbase_m', ...
    'sourceVehicleFrontMassFraction', 'sourceVehicleCgHeight_m', ...
    'sourceVehicleYawInertia_kgm2'};
actual = zeros(size(expected));
for index = 1:numel(fields)
    assert(isfield(performanceMap.meta, fields{index}), ...
        'lts:model:MapConfiguration', ...
        'Level 1.3 map lacks vehicle identity field %s.', fields{index});
    actual(index) = performanceMap.meta.(fields{index});
end
assert(all(abs(actual - expected) <= 1e-12 .* max(1, abs(expected))), ...
    'lts:model:MapConfiguration', ...
    'Level 1.3 performance map belongs to a different vehicle definition.');
equivalent = lts.model.singleTrackSlip.equivalentVehicle(vehicle);
base = lts.model.dualTrackSlip.create(equivalent, performanceMap);
model = base;
model.name = sprintf('Level 1.3 Single Track Slip - %s', ...
    lts.tire.create(vehicle).type);
model.level = '1.3';
model.vehicle = vehicle;
model.operatingPoint = @(speed_mps, ax_mps2, ay_mps2) ...
    lts.model.singleTrackSlip.operatingPoint(vehicle, speed_mps, ...
    ax_mps2, ay_mps2);
end
