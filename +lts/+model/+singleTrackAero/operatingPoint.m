function point = operatingPoint(vehicle, speed_mps, longitudinalAcceleration_mps2, lateralAcceleration_mps2)
%OPERATINGPOINT Named Level 1.2 state and force-balance diagnostics.

validateattributes(speed_mps, {'numeric'}, {'scalar', 'real', 'finite', 'nonnegative'});
validateattributes(longitudinalAcceleration_mps2, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(lateralAcceleration_mps2, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
state = lts.model.singleTrackAero.calculateState(vehicle, speed_mps, ...
    longitudinalAcceleration_mps2, lateralAcceleration_mps2);
mass_kg = vehicle.mass.total_kg;
frontFraction = vehicle.geometry.frontMassFraction;
distanceCgToFront_m = vehicle.geometry.wheelbase_m * (1 - frontFraction);
distanceCgToRear_m = vehicle.geometry.wheelbase_m * frontFraction;

point = state;
point.speed_mps = speed_mps;
point.longitudinalAcceleration_mps2 = longitudinalAcceleration_mps2;
point.lateralAcceleration_mps2 = lateralAcceleration_mps2;
point.residuals.longitudinalForce_N = state.frontLongitudinalForce_N ...
    + state.rearLongitudinalForce_N - state.aero.drag_N ...
    - mass_kg * longitudinalAcceleration_mps2;
point.residuals.lateralForce_N = state.frontLateralForce_N ...
    + state.rearLateralForce_N - mass_kg * lateralAcceleration_mps2;
point.residuals.yawMoment_Nm = distanceCgToFront_m ...
    * state.frontLateralForce_N - distanceCgToRear_m ...
    * state.rearLateralForce_N - sum([vehicle.geometry.frontTrack_m / 2, ...
    -vehicle.geometry.frontTrack_m / 2, vehicle.geometry.rearTrack_m / 2, ...
    -vehicle.geometry.rearTrack_m / 2] .* state.longitudinalForces_N) ...
    - vehicle.controls.targetYawMoment_Nm;
end
