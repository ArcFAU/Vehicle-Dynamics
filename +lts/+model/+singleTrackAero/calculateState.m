function state = calculateState(vehicle, speed_mps, longitudinalAcceleration_mps2, lateralAcceleration_mps2, peakEnvelope)
%CALCULATESTATE Vectorized Level 1.2 front/rear forces and normal loads.

if nargin < 5
    peakEnvelope = lts.tire.createPeakEnvelope(vehicle);
end

aero = lts.aerodynamics.forces(vehicle.aerodynamics, speed_mps);
mass_kg = vehicle.mass.total_kg;
frontFraction = vehicle.geometry.frontMassFraction;
wheelbase_m = vehicle.geometry.wheelbase_m;
loadTransfer_N = (mass_kg .* longitudinalAcceleration_mps2 ...
    .* vehicle.geometry.cgHeight_m + aero.drag_N ...
    .* vehicle.aerodynamics.dragApplicationHeight_m) / wheelbase_m;
state.frontNormalLoad_N = mass_kg * 9.81 * frontFraction ...
    + aero.frontDownforce_N - loadTransfer_N;
state.rearNormalLoad_N = mass_kg * 9.81 * (1 - frontFraction) ...
    + aero.rearDownforce_N + loadTransfer_N;
frontTireNormalLoad_N = max(state.frontNormalLoad_N / 2, 0);
rearTireNormalLoad_N = max(state.rearNormalLoad_N / 2, 0);
state.frontLateralForce_N = mass_kg .* lateralAcceleration_mps2 * frontFraction;
state.rearLateralForce_N = mass_kg .* lateralAcceleration_mps2 ...
    * (1 - frontFraction);

requiredTireForce_N = mass_kg .* longitudinalAcceleration_mps2 + aero.drag_N;
useIdealDrive = strcmp(vehicle.controls.driveAllocation.mode, 'ideal');
useIdealBrake = strcmp(vehicle.controls.brakeAllocation.mode, 'ideal');
if useIdealDrive || useIdealBrake
    normalLoadsPerWheel_N = [frontTireNormalLoad_N, ...
        frontTireNormalLoad_N, rearTireNormalLoad_N, ...
        rearTireNormalLoad_N];
    lateralForcesPerWheel_N = [state.frontLateralForce_N / 2, ...
        state.frontLateralForce_N / 2, state.rearLateralForce_N / 2, ...
        state.rearLateralForce_N / 2];
    cambers_rad = repmat([vehicle.suspension.frontCamber_rad, ...
        -vehicle.suspension.frontCamber_rad, ...
        vehicle.suspension.rearCamber_rad, ...
        -vehicle.suspension.rearCamber_rad], ...
        size(normalLoadsPerWheel_N, 1), 1);
    capacities_N = lts.tire.directionalLongitudinalCapacity( ...
        peakEnvelope, normalLoadsPerWheel_N, ...
        lateralForcesPerWheel_N, cambers_rad);
    longitudinalForces_N = zeros(size(capacities_N));
    allocationFeasible = false(size(requiredTireForce_N));
    allocations = cell(numel(requiredTireForce_N), 1);
    for row = 1:numel(requiredTireForce_N)
        operation = "drive";
        if requiredTireForce_N(row) < 0
            operation = "brake";
        end
        allocation = lts.control.allocateLongitudinalForces(vehicle, ...
            speed_mps(row), capacities_N(row, :), ...
            lateralForcesPerWheel_N(row, :), ...
            requiredTireForce_N(row), operation);
        longitudinalForces_N(row, :) = allocation.forces_N;
        allocationFeasible(row) = allocation.feasible;
        allocations{row} = allocation;
    end
    state.frontLongitudinalForce_N = sum(longitudinalForces_N(:, 1:2), 2);
    state.rearLongitudinalForce_N = sum(longitudinalForces_N(:, 3:4), 2);
    state.longitudinalForces_N = longitudinalForces_N;
    state.allocation = allocations;
else
    frontForceFraction = vehicle.powertrain.frontDriveForceFraction ...
        * ones(size(requiredTireForce_N));
    braking = longitudinalAcceleration_mps2 < 0;
    frontForceFraction(braking) = vehicle.brakes.frontForceFraction;
    state.frontLongitudinalForce_N = requiredTireForce_N .* frontForceFraction;
    state.rearLongitudinalForce_N = requiredTireForce_N ...
        .* (1 - frontForceFraction);
    state.longitudinalForces_N = [state.frontLongitudinalForce_N / 2, ...
        state.frontLongitudinalForce_N / 2, ...
        state.rearLongitudinalForce_N / 2, ...
        state.rearLongitudinalForce_N / 2];
    allocationFeasible = true(size(requiredTireForce_N));
end

state.frontUtilization = lts.tire.directionalUtilization(peakEnvelope, ...
    frontTireNormalLoad_N, state.frontLongitudinalForce_N / 2, ...
    state.frontLateralForce_N / 2, vehicle.suspension.frontCamber_rad);
state.rearUtilization = lts.tire.directionalUtilization(peakEnvelope, ...
    rearTireNormalLoad_N, state.rearLongitudinalForce_N / 2, ...
    state.rearLateralForce_N / 2, vehicle.suspension.rearCamber_rad);
drive = lts.powertrain.maximumDriveForce(vehicle.powertrain, speed_mps);
state.driveForceAvailable_N = drive.maximumForce_N;
state.driveForceRequired_N = max(requiredTireForce_N, 0);
state.aero = aero;
state.feasible = state.frontNormalLoad_N > 0 & state.rearNormalLoad_N > 0 ...
    & state.frontUtilization <= 1 + 1e-12 ...
    & state.rearUtilization <= 1 + 1e-12 ...
    & allocationFeasible ...
    & state.driveForceRequired_N <= state.driveForceAvailable_N + 1e-9;
end
