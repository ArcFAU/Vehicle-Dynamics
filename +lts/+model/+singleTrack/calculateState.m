function state = calculateState(vehicle, longitudinalAcceleration_mps2, lateralAcceleration_mps2)
%CALCULATESTATE Vectorized axle state used by limits and diagnostics.

validateattributes(longitudinalAcceleration_mps2, {'numeric'}, ...
    {'real', 'finite'});
validateattributes(lateralAcceleration_mps2, {'numeric'}, ...
    {'real', 'finite', 'size', size(longitudinalAcceleration_mps2)});

mass_kg = vehicle.mass.total_kg;
gravity_mps2 = 9.81;
wheelbase_m = vehicle.geometry.wheelbase_m;
frontMassFraction = vehicle.geometry.frontMassFraction;
longitudinalLoadTransfer_N = mass_kg .* longitudinalAcceleration_mps2 ...
    .* vehicle.geometry.cgHeight_m ./ wheelbase_m;

state.frontNormalLoad_N = mass_kg * gravity_mps2 * frontMassFraction ...
    - longitudinalLoadTransfer_N;
state.rearNormalLoad_N = mass_kg * gravity_mps2 * (1 - frontMassFraction) ...
    + longitudinalLoadTransfer_N;
state.frontLateralForce_N = mass_kg .* lateralAcceleration_mps2 ...
    .* frontMassFraction;
state.rearLateralForce_N = mass_kg .* lateralAcceleration_mps2 ...
    .* (1 - frontMassFraction);

frontLongitudinalFraction = vehicle.powertrain.frontDriveForceFraction ...
    * ones(size(longitudinalAcceleration_mps2));
braking = longitudinalAcceleration_mps2 < 0;
frontLongitudinalFraction(braking) = vehicle.brakes.frontForceFraction;
rearLongitudinalFraction = 1 - frontLongitudinalFraction;
totalLongitudinalForce_N = mass_kg .* longitudinalAcceleration_mps2;
state.frontLongitudinalForce_N = totalLongitudinalForce_N ...
    .* frontLongitudinalFraction;
state.rearLongitudinalForce_N = totalLongitudinalForce_N ...
    .* rearLongitudinalFraction;

state.frontUtilization = lts.tire.utilization(vehicle.tireEnvelope, ...
    state.frontNormalLoad_N / 2, state.frontLongitudinalForce_N / 2, ...
    state.frontLateralForce_N / 2);
state.rearUtilization = lts.tire.utilization(vehicle.tireEnvelope, ...
    state.rearNormalLoad_N / 2, state.rearLongitudinalForce_N / 2, ...
    state.rearLateralForce_N / 2);
state.feasible = state.frontNormalLoad_N >= 0 ...
    & state.rearNormalLoad_N >= 0 ...
    & state.frontUtilization <= 1 + 1e-12 ...
    & state.rearUtilization <= 1 + 1e-12;
end
