function validateTrack(track)
%VALIDATETRACK Validate the common track data contract.

validateattributes(track, {'struct'}, {'scalar'}, mfilename, 'track');
assert(isfield(track, 'distance_m') && isfield(track, 'curvature_1pm') ...
    && isfield(track, 'isClosed'), 'lts:validation:TrackFields', ...
    'Track requires distance_m, curvature_1pm and isClosed.');

validateattributes(track.distance_m, {'numeric'}, ...
    {'column', 'real', 'finite', 'nonempty'}, mfilename, 'distance_m');
validateattributes(track.curvature_1pm, {'numeric'}, ...
    {'column', 'real', 'finite', 'numel', numel(track.distance_m)}, ...
    mfilename, 'curvature_1pm');
validateattributes(track.isClosed, {'logical'}, {'scalar'}, mfilename, 'isClosed');
assert(numel(track.distance_m) >= 2 && track.distance_m(1) == 0 ...
    && all(diff(track.distance_m) > 0), 'lts:validation:TrackDistance', ...
    'distance_m must start at zero and be strictly increasing.');
end
