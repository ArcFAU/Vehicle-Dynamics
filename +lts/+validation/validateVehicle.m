    'aerodynamics.airDensity_kgpm3');
validateattributes(vehicle.aerodynamics.dragApplicationHeight_m, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'nonnegative'}, mfilename, ...
    'aerodynamics.dragApplicationHeight_m');
