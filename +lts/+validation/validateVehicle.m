mustBePositiveFiniteScalar(vehicle.geometry.cgHeight_m, 'geometry.cgHeight_m');
mustBePositiveFiniteScalar(vehicle.tireApproximation.frictionCoefficient, ...
    'tireApproximation.frictionCoefficient');
