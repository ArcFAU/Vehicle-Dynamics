    {'scalar', 'real', 'finite', '<=', 0}, mfilename, ...
    'tireEnvelope.loadSensitivityExponent');
validateattributes(vehicle.tireEnvelope.combinedForceExponent, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 1}, mfilename, ...
    'tireEnvelope.combinedForceExponent');
