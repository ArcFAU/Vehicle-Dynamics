    'tireEnvelope.referenceNormalLoad_N'
    'tireEnvelope.frictionCoefficientAtReferenceLoad'
    'tireEnvelope.loadSensitivityExponent'
    'tireEnvelope.combinedForceExponent'
    'tireModel.active'
    'tireModel.fittedCombinedSlip.name'
    'tireModel.fittedCombinedSlip.file'
    'tireModel.fittedCombinedSlip.lateralScale'
    'tireModel.fittedCombinedSlip.longitudinalScale'
    'tireModel.fittedCombinedSlip.version'
    'tireModel.tmeasyAdtm.name'
    'tireModel.tmeasyAdtm.parameterSet'
    'tireModel.tmeasyAdtm.muScale'
    'tireModel.tmeasyAdtm.version'
    'tireModel.tmeasyAdtm.parameterVersion'
    'brakes.frontForceFraction'
    'controls.driveAllocation.mode'
    'controls.brakeAllocation.mode'
    'controls.regenAllocation.mode'
    'controls.regenAllocation.fixedUtilizationFactor'
    'controls.targetYawMoment_Nm'
    'powertrain.drivenAxle'
    'powertrain.maximumPower_W'
    'powertrain.maximumMotorPower_W'
    'powertrain.maximumMotorTorque_Nm'
    'powertrain.maximumMotorSpeed_rpm'
    'powertrain.gearRatio'
    'powertrain.gearboxEfficiency'
    'powertrain.drivenWheelCount'
