    validAllocationModes)), 'lts:validation:BrakeAllocation', ...
    'controls.brakeAllocation.mode must be fixed or ideal.');
assert(any(strcmp(vehicle.controls.regenAllocation.mode, ...
    validAllocationModes)), 'lts:validation:RegenAllocation', ...
    'controls.regenAllocation.mode must be fixed or ideal.');
validateattributes(vehicle.controls.regenAllocation.fixedUtilizationFactor, ...
    {'numeric'}, {'scalar', 'real', 'finite', '>=', 0, '<=', 1}, ...
    mfilename, 'controls.regenAllocation.fixedUtilizationFactor');
validateattributes(vehicle.controls.targetYawMoment_Nm, {'numeric'}, ...
    {'scalar', 'real', 'finite'}, mfilename, ...
    'controls.targetYawMoment_Nm');
validDrivenAxles = {'front', 'rear', 'all'};
assert(any(strcmp(vehicle.powertrain.drivenAxle, validDrivenAxles)), ...
    'lts:validation:DrivenAxle', ...
    'powertrain.drivenAxle must be front, rear or all.');
mustBePositiveFiniteScalar(vehicle.powertrain.maximumPower_W, ...
    'powertrain.maximumPower_W');
mustBePositiveFiniteScalar(vehicle.powertrain.maximumMotorPower_W, ...
    'powertrain.maximumMotorPower_W');
mustBePositiveFiniteScalar(vehicle.powertrain.maximumMotorTorque_Nm, ...
    'powertrain.maximumMotorTorque_Nm');
mustBePositiveFiniteScalar(vehicle.powertrain.maximumMotorSpeed_rpm, ...
    'powertrain.maximumMotorSpeed_rpm');
mustBePositiveFiniteScalar(vehicle.powertrain.gearRatio, ...
    'powertrain.gearRatio');
validateattributes(vehicle.powertrain.gearboxEfficiency, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>', 0, '<=', 1}, mfilename, ...
    'powertrain.gearboxEfficiency');
validateattributes(vehicle.powertrain.drivenWheelCount, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'integer', '>=', 1, '<=', 4}, ...
    mfilename, 'powertrain.drivenWheelCount');
validateattributes(vehicle.powertrain.motorCount, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'integer', '>=', 1, '<=', 4}, ...
    mfilename, 'powertrain.motorCount');
