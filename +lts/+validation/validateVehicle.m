    {'scalar', 'real', 'finite', 'positive'}, mfilename, ...
    'tireModel.tmeasyAdtm.muScale');
validateattributes(vehicle.geometry.frontMassFraction, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>', 0, '<', 1}, mfilename, ...
    'geometry.frontMassFraction');
validateattributes(vehicle.brakes.frontForceFraction, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<=', 1}, mfilename, ...
    'brakes.frontForceFraction');
