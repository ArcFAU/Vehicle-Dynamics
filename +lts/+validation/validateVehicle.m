    {'numeric'}, {'scalar', 'real', 'finite', 'nonnegative'}, mfilename, ...
    'suspension.front.antiRollStiffness_NmPerRad');
mustBePositiveFiniteScalar(vehicle.suspension.rear.springRate_Npm, ...
    'suspension.rear.springRate_Npm');
mustBePositiveFiniteScalar(...
    vehicle.suspension.rear.motionRatioWheelPerDamper, ...
    'suspension.rear.motionRatioWheelPerDamper');
validateattributes(vehicle.suspension.rear.antiRollStiffness_NmPerRad, ...
    {'numeric'}, {'scalar', 'real', 'finite', 'nonnegative'}, mfilename, ...
    'suspension.rear.antiRollStiffness_NmPerRad');
