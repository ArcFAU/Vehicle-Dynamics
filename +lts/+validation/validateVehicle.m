end

function present = hasFieldPath(value, fieldPath)
parts = split(fieldPath, '.');
present = true;
for index = 1:numel(parts)
    if ~isstruct(value) || ~isfield(value, parts{index})
        present = false;
        return
    end
    value = value.(parts{index});
end
end

function mustBePositiveFiniteScalar(value, name)
validateattributes(value, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'}, mfilename, name);
end

function validateCurve(breakpoints, values, name)
assert(isnumeric(breakpoints) && isvector(breakpoints) ...
    && numel(breakpoints) >= 2 && all(isfinite(breakpoints)) ...
    && all(diff(breakpoints) > 0) ...
    && breakpoints(1) >= 0 && breakpoints(end) <= 1, ...
    'lts:validation:SocCurve', ...
    '%s breakpoints must increase within [0, 1].', name);
assert(isnumeric(values) && isvector(values) ...
    && numel(values) == numel(breakpoints) && all(isfinite(values)) ...
    && all(values >= 0), 'lts:validation:SocCurve', ...
    '%s values must be finite, nonnegative and match the breakpoints.', name);
end

function validateValidityLimits(validity)
mustBePositiveFiniteScalar(validity.maximumRoadWheelSteeringAngle_rad, ...
    'validity.maximumRoadWheelSteeringAngle_rad');
validateIncreasingPair(validity.minimumSlipAngle_rad, ...
    validity.maximumSlipAngle_rad, 'validity slip-angle limits');
validateIncreasingPair(validity.minimumSlipRatio, ...
    validity.maximumSlipRatio, 'validity slip-ratio limits');
validateIncreasingPair(validity.minimumValidatedNormalLoad_N, ...
    validity.maximumValidatedNormalLoad_N, 'validity normal-load limits');
assert(validity.minimumValidatedNormalLoad_N >= 0, ...
    'lts:validation:ValidityLimits', ...
    'Minimum validated normal load must be nonnegative.');
validateIncreasingPair(validity.minimumRideHeight_mm, ...
    validity.maximumRideHeight_mm, 'validity ride-height limits');
validateattributes(validity.solverBoundMarginFraction, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<', 0.5}, mfilename, ...
    'validity.solverBoundMarginFraction');
end

function validateIncreasingPair(minimumValue, maximumValue, name)
validateattributes(minimumValue, {'numeric'}, ...
    {'scalar', 'real', 'finite'}, mfilename, [name, ' minimum']);
validateattributes(maximumValue, {'numeric'}, ...
    {'scalar', 'real', 'finite'}, mfilename, [name, ' maximum']);
assert(minimumValue < maximumValue, 'lts:validation:ValidityLimits', ...
    '%s must be strictly increasing.', name);
end
