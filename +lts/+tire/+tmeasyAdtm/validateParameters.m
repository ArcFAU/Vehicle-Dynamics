function validateParameters(tir)
%VALIDATEPARAMETERS Apply the original ADTM TMeasy plausibility checks.

required = {'r_0', 'b_0', 'c_x', 'c_y', 'c_z', 'F_zN', 'F_zMax', ...
    'dF_x01', 'dF_x02', 's_xMA1', 's_xMA2', 'F_xMA1', 'F_xMA2', ...
    's_xMB1', 's_xMB2', 'F_xMB1', 'F_xMB2', 'dF_y01', 'dF_y02', ...
    's_yM1', 's_yM2', 'F_yM1', 'F_yM2'};
for index = 1:numel(required)
    assert(isfield(tir, required{index}), 'lts:tire:TMeasyParameters', ...
        'Missing TMeasy parameter %s.', required{index});
end
assert(2 * tir.F_xMA1 >= tir.F_xMA2 ...
    && 2 * tir.F_xMB1 >= tir.F_xMB2 ...
    && 2 * tir.F_yM1 >= tir.F_yM2, ...
    'lts:tire:TMeasyParameters', ...
    'Implausible peak-force load interpolation.');
assert(tir.dF_x01 >= 2 * tir.F_xMA1 / tir.s_xMA1 ...
    && tir.dF_x01 >= 2 * tir.F_xMB1 / tir.s_xMB1 ...
    && tir.dF_x02 >= 2 * tir.F_xMA2 / tir.s_xMA2 ...
    && tir.dF_x02 >= 2 * tir.F_xMB2 / tir.s_xMB2 ...
    && tir.dF_y01 >= 2 * tir.F_yM1 / tir.s_yM1 ...
    && tir.dF_y02 >= 2 * tir.F_yM2 / tir.s_yM2, ...
    'lts:tire:TMeasyParameters', ...
    'Implausible initial-slip stiffness.');
end
