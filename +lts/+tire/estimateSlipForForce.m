function estimate = estimateSlipForForce(model, normalLoad_N, ...
        camberAngle_rad, targetLongitudinalForce_N, ...
        targetLateralForce_N, speed_mps)
%ESTIMATESLIPFORFORCE Provide a model-specific nonlinear-solver start value.

switch model.type
    case 'fittedCombinedSlip'
        p = lts.tire.magicFormulaParameters(model.parameters, ...
            normalLoad_N, camberAngle_rad);
        estimate.slipRatio = targetLongitudinalForce_N ...
            / abs(p.longitudinal.D_N) * p.longitudinal.peakSlip;
        estimate.slipAngle_rad = targetLateralForce_N ...
            / abs(p.lateral.D_N) * p.lateral.peakSlip;
    case 'tmeasyAdtm'
        zero = lts.tire.tmeasyAdtm.evaluate(model.parameters, ...
            normalLoad_N, camberAngle_rad, 0, 0, speed_mps, model.muScale);
        estimate.slipRatio = targetLongitudinalForce_N ...
            / max(zero.dFx0_N, eps);
        estimate.slipAngle_rad = atan(targetLateralForce_N ...
            / max(zero.dFy0_N, eps));
    otherwise
        error('lts:tire:UnknownModel', 'Unknown tire model: %s.', model.type);
end
estimate.slipRatio = max(min(estimate.slipRatio, 0.3), -0.3);
estimate.slipAngle_rad = max(min(estimate.slipAngle_rad, ...
    deg2rad(25)), -deg2rad(25));
end
