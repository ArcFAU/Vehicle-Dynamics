function efficiency = conversionEfficiencies(vehicle, speed_mps, ...
        wheelForce_N, soc, direction)
%CONVERSIONEFFICIENCIES Evaluate constant factors or component maps.

arguments
    vehicle (1, 1) struct
    speed_mps double
    wheelForce_N double {mustBeReal, mustBeFinite}
    soc double {mustBeReal, mustBeFinite}
    direction (1, 1) string {mustBeMember(direction, ["drive", "regen"])}
end

model = vehicle.energy.efficiencyModel;
switch model.mode
    case 'constant'
        if direction == "drive"
            efficiency.motor = vehicle.energy.motorEfficiency ...
                * ones(size(speed_mps));
            efficiency.inverter = vehicle.energy.inverterEfficiency ...
                * ones(size(speed_mps));
            efficiency.battery = ...
                vehicle.energy.batteryDischargeEfficiency ...
                * ones(size(speed_mps));
        else
            efficiency.motor = vehicle.energy.regenMotorEfficiency ...
                * ones(size(speed_mps));
            efficiency.inverter = vehicle.energy.inverterEfficiency ...
                * ones(size(speed_mps));
            efficiency.battery = vehicle.energy.batteryChargeEfficiency ...
                * ones(size(speed_mps));
        end
    case 'map'
        motorSpeed_rpm = speed_mps ...
            / vehicle.powertrain.effectiveTireRadius_m ...
            * vehicle.powertrain.gearRatio * 60 / (2 * pi);
        motorTorque_Nm = abs(wheelForce_N) ...
            * vehicle.powertrain.effectiveTireRadius_m ...
            / vehicle.powertrain.gearRatio ...
            / vehicle.powertrain.gearboxEfficiency ...
            / vehicle.powertrain.motorCount;
        if direction == "drive"
            motorValues = model.motor.driveValues;
            inverterValues = model.inverter.driveValues;
            batteryValues = model.battery.dischargeValues;
        else
            motorValues = model.motor.regenValues;
            inverterValues = model.inverter.regenValues;
            batteryValues = model.battery.chargeValues;
        end
        efficiency.motor = interpolateMap(model.motor.speed_rpm, ...
            model.motor.torque_Nm, motorValues, motorSpeed_rpm, motorTorque_Nm);
        mechanicalPower_W = abs(wheelForce_N .* speed_mps) ...
            / vehicle.powertrain.gearboxEfficiency;
        efficiency.inverter = interpolateMap(model.inverter.power_W, ...
            model.inverter.soc, inverterValues, mechanicalPower_W, soc);
        efficiency.battery = interpolateMap(model.battery.power_W, ...
            model.battery.soc, batteryValues, mechanicalPower_W, soc);
    otherwise
        error('lts:energy:EfficiencyModel', ...
            'Unknown efficiency model: %s.', model.mode);
end
efficiency.gearbox = vehicle.powertrain.gearboxEfficiency ...
    * ones(size(speed_mps));
efficiency.total = efficiency.gearbox .* efficiency.motor ...
    .* efficiency.inverter .* efficiency.battery;
assert(all(isfinite(efficiency.total)) ...
    && all(efficiency.total > 0 & efficiency.total <= 1), ...
    'lts:energy:EfficiencyMap', ...
    'Interpolated conversion efficiencies must be in (0, 1].');
end

function values = interpolateMap(xAxis, yAxis, map, xQuery, yQuery)
assert(numel(xAxis) >= 2 && numel(yAxis) >= 2 ...
    && isequal(size(map), [numel(yAxis), numel(xAxis)]) ...
    && all(diff(xAxis) > 0) && all(diff(yAxis) > 0), ...
    'lts:energy:EfficiencyMap', ...
    'Map axes must increase and map size must be [numel(y), numel(x)].');
xQuery = min(max(xQuery, xAxis(1)), xAxis(end));
yQuery = min(max(yQuery, yAxis(1)), yAxis(end));
values = interp2(xAxis, yAxis, map, xQuery, yQuery, 'linear');
end
