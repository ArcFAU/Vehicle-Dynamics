function events = fsg2026(options)
%FSG2026 Configure FSG dynamic tracks independently from the vehicle model.
% Replace TrackFiles fields or create another event-config function for a
% different competition. Project track inputs are read only.

arguments
    options.TrackFiles (1, 1) struct = struct()
end

files = lts.io.trackCatalog();
overrideNames = fieldnames(options.TrackFiles);
for index = 1:numel(overrideNames)
    files.(overrideNames{index}) = char(options.TrackFiles.(overrideNames{index}));
end

events(1) = lts.events.createDefinition( ...
    Id="acceleration", Name="Acceleration", Discipline="acceleration", ...
    Mode="manual", TrackFile=files.acceleration, IsClosed=false, ...
    InitialSpeed_mps=0, FinalSpeed_mps=100);
events(2) = lts.events.createDefinition( ...
    Id="skidpad", Name="Skidpad", Discipline="skidpad", ...
    Mode="manual", TrackFile=files.skidpad, IsClosed=true, ...
    TimingWindows_m=[52, 105; 157, 210], ...
    TimingAggregation="meanWindows");
events(3) = lts.events.createDefinition( ...
    Id="autocross", Name="Autocross", Discipline="autocross", ...
    Mode="manual", TrackFile=files.autocross, IsClosed=false, ...
    InitialSpeed_mps=0, FinalSpeed_mps=100);
events(4) = lts.events.createDefinition( ...
    Id="endurance", Name="Endurance", Discipline="endurance", ...
    Mode="manual", TrackFile=files.endurance, IsClosed=true, ...
    TimeMultiplier=18);
events(5) = lts.events.createDefinition( ...
    Id="dvAcceleration", Name="Driverless Acceleration", ...
    Discipline="acceleration", Mode="driverless", ...
    TrackFile=files.dvAcceleration, IsClosed=false, ...
    InitialSpeed_mps=0, FinalSpeed_mps=100);
events(6) = lts.events.createDefinition( ...
    Id="dvSkidpad", Name="Driverless Skidpad", ...
    Discipline="skidpad", Mode="driverless", ...
    TrackFile=files.dvSkidpad, IsClosed=true, ...
    TimingWindows_m=[52, 105; 157, 210], ...
    TimingAggregation="meanWindows");
end
