function summary = validateCase(config, track, options)
%VALIDATECASE Validate and summarize a case without running a simulation.

arguments
    config (1, 1) struct
    track (1, 1) struct
    options.Display (1, 1) logical = true
end

required = {'schema', 'vehicle', 'modelId', 'level', 'strategy', ...
    'includeEnergy', 'includeYawInertia', 'maximumSpeed_mps', ...
    'initialSpeed_mps', 'finalSpeed_mps', 'performanceMap', 'trackLocal'};
for index = 1:numel(required)
    assert(isfield(config, required{index}), 'lts:config:CaseConfiguration', ...
        'Missing case configuration field: %s.', required{index});
end
assert(strcmp(config.schema, 'lts.case.v1'), ...
    'lts:config:CaseConfiguration', ...
    'Unsupported case configuration schema: %s.', config.schema);
lts.validation.validateVehicle(config.vehicle);
lts.validation.validateTrack(track);
definition = lts.model.registry(config.modelId);
strategy = string(config.strategy);
assert(strcmp(config.level, definition.level), ...
    'lts:config:CaseConfiguration', ...
    'Configured level does not match registered model "%s".', config.modelId);
assert(any(strategy == definition.strategies), ...
    'lts:config:CaseConfiguration', ...
    'Strategy "%s" is unavailable for model "%s".', strategy, config.modelId);
if any(definition.tireRequirement == ...
        ["fittedCombinedSlip", "tmeasyAdtm"])
    assert(string(config.vehicle.tireModel.active) == ...
        definition.tireRequirement, 'lts:config:CaseConfiguration', ...
        'Model "%s" requires tire model "%s", but vehicle selects "%s".', ...
        config.modelId, definition.tireRequirement, ...
        config.vehicle.tireModel.active);
end
assert(~config.includeYawInertia || ...
    (strategy == "trackLocal" && definition.supportsYawAudit), ...
    'lts:config:CaseConfiguration', ...
    'Yaw-inertia audit is unavailable for this model and strategy.');
if strategy == "mapped"
    assert(~isempty(config.performanceMap), ...
        'lts:config:CaseConfiguration', ...
        'Mapped execution requires an explicit performance map.');
    definition.factory(config.vehicle, strategy, config.performanceMap);
else
    assert(isempty(config.performanceMap), ...
        'lts:config:CaseConfiguration', ...
        'A performance map is only valid for mapped execution.');
end

trackName = "unnamed track";
if isfield(track, 'meta') && isfield(track.meta, 'name')
    trackName = string(track.meta.name);
end
workload = "direct evaluation";
if strategy == "mapped"
    workload = "reuse and validate supplied map";
elseif strategy == "trackLocal"
    workload = string(sprintf( ...
        'build map: %d speed rows, %d boundary iterations', ...
        config.trackLocal.speedRows, config.trackLocal.boundaryIterations));
end
summary = table(string(definition.id), string(definition.level), strategy, ...
    string(definition.mapType), string(definition.tireRequirement), ...
    logical(config.includeEnergy), logical(config.includeYawInertia), ...
    workload, trackName, 'VariableNames', ...
    {'modelId', 'level', 'strategy', 'mapType', ...
    'tireRequirement', 'includeEnergy', 'includeYawInertia', ...
    'workload', 'track'});
if options.Display
    disp(summary);
end
end
