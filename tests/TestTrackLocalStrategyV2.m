classdef TestTrackLocalStrategyV2 < matlab.unittest.TestCase
    properties
        vehicle
        track
    end

    methods (TestClassSetup)
        function createInputs(testCase)
            testCase.vehicle = FAUmaxTauV2();
            testCase.track.distance_m = (0:10:40).';
            testCase.track.curvature_1pm = [0; 0.02; -0.02; 0.01; 0];
            testCase.track.isClosed = true;
            testCase.track.meta.name = 'Track-local test loop';
        end
    end

    methods (Test)
        function localMapUsesTrackSpecificRange(testCase)
            [map, info] = lts.design.buildTrackLocalMap(...
                testCase.vehicle, testCase.track, Model="dualTrackSlipFitted", ...
                MaximumSpeed_mps=15, SpeedRowCount=2, ...
                LateralFractions=[0, 1], BoundaryIterations=3);

            testCase.verifyEqual(map.meta.scope, 'trackLocal');
            testCase.verifyEqual(map.meta.trackName, ...
                testCase.track.meta.name);
            testCase.verifyEqual(map.meta.gridSelection, ...
                'seedLapQuantiles');
            testCase.verifySize(map.speedGrid_mps, [1, 2]);
            testCase.verifyLessThanOrEqual(map.speedGrid_mps(end), 15);
            testCase.verifyEqual(info.boundariesCalculated, 20);
        end

        function runCaseSupportsTrackLocalLevel21(testCase)
            config = lts.config.createCase(Vehicle=testCase.vehicle, ...
                Model="dualTrackSlipFitted", Strategy="trackLocal", ...
                MaximumSpeed_mps=15, TrackLocalSpeedRows=2, ...
                TrackLocalLateralFractions=[0, 1], ...
                TrackLocalBoundaryIterations=3, ...
                TrackLocalAuditPointCount=2, IncludeYawInertia=true, ...
                IncludeEnergy=false, InitialSpeed_mps=0, FinalSpeed_mps=Inf);
            result = lts.design.runCase(config, testCase.track);

            testCase.verifyTrue(result.lap.meta.converged);
            testCase.verifyEqual(result.meta.strategy, 'trackLocal');
            testCase.verifyEqual(result.meta.trackLocal.scope, 'trackLocal');
            testCase.verifyGreaterThan(result.meta.trackLocal.buildTime_s, 0);
            testCase.verifyTrue(...
                result.meta.trackLocal.audit.allConfirmedFeasible);
            testCase.verifyTrue(...
                result.meta.trackLocal.audit.includesYawInertia);
            testCase.verifyEqual(result.meta.trackLocal.modelId, ...
                'dualTrackSlipFitted');
        end

        function level13UsesSameExecutionStrategy(testCase)
            config = lts.config.createCase(Vehicle=testCase.vehicle, ...
                Model="singleTrackSlip", Strategy="trackLocal", ...
                MaximumSpeed_mps=15, TrackLocalSpeedRows=2, ...
                TrackLocalLateralFractions=[0, 1], ...
                TrackLocalBoundaryIterations=3, ...
                TrackLocalAuditPointCount=2, IncludeYawInertia=false, ...
                IncludeEnergy=false, InitialSpeed_mps=0, FinalSpeed_mps=Inf);
            result = lts.design.runCase(config, testCase.track);

            testCase.verifyTrue(result.lap.meta.converged);
            testCase.verifyEqual(result.lap.meta.modelLevel, '1.3');
            testCase.verifyEqual(result.yawDemand.couplingMode, ...
                'diagnosticOnly');
        end

        function envelopeLevelsRejectTrackLocal(testCase)
            testCase.verifyError(@() lts.config.createCase( ...
                Vehicle=testCase.vehicle, Model="pointMassAero", ...
                Strategy="trackLocal", IncludeEnergy=false, ...
                IncludeYawInertia=false, MaximumSpeed_mps=15, ...
                InitialSpeed_mps=0, FinalSpeed_mps=Inf), ...
                'lts:config:ModelStrategy');
        end
    end
end
