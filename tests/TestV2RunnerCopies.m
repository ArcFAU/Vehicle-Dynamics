classdef TestV2RunnerCopies < matlab.unittest.TestCase
    methods (Test)
        function allParallelRunnerFilesExist(testCase)
            root=fileparts(fileparts(mfilename('fullpath')));
            names={ ...
                'runModelComparisonV2.m','tools/comparisons/runPowertrainComparisonV2.m', ...
                'tools/comparisons/runPowertrainEnergyComparisonV2.m', ...
                'tools/comparisons/runTorqueAllocationComparisonV2.m', ...
                'tools/comparisons/runSingleTrackSlipComparisonV2.m', ...
                'tools/comparisons/runSlipModelComparisonV2.m','tools/comparisons/runTireModelComparisonV2.m', ...
                'tools/comparisons/runRollStiffnessComparisonV2.m', ...
                'tools/comparisons/runRollStiffnessSlipComparisonV2.m', ...
                'tools/comparisons/runChassisStiffnessComparisonV2.m', ...
                'tools/comparisons/runChassisStiffnessSlipComparisonV2.m', ...
                'runSensitivityStudyV2.m','runEnergyReportV2.m'};
            for k=1:numel(names)
                testCase.verifyTrue(isfile(fullfile(root,names{k})),names{k});
            end
            testCase.verifyTrue(isfile(fullfile(root,'config', ...
                'sensitivityStudyCaseV2.m')));
        end

        function directNoArgumentRunnerExecutes(testCase)
            comparison=runModelComparisonV2();
            testCase.verifyEqual(numel(comparison),3);
            testCase.verifyTrue(all([comparison.lapTime_s]>0));
        end

        function directEventBuildersExposeThreeFamilies(testCase)
            vehicle=FAUmaxTauV2();
            families=["pointMass","singleTrack","dualTrack"];
            for k=1:numel(families)
                [model,effective]=lts.v2.buildDirectModel(Vehicle=vehicle, ...
                    Model=families(k),Aero=true, ...
                    LoadTransfer=families(k)~="pointMass",Energy=false, ...
                    YawInertia=false,ChassisTorsion=false);
                testCase.verifyTrue(isfield(model,'accelerationLimits'));
                testCase.verifyEqual(string(effective.model),families(k));
            end
        end

        function sensitivityTemplateUsesPublicV2Selection(testCase)
            root=fileparts(fileparts(mfilename('fullpath')));
            addpath(fullfile(root,'config'));
            config=sensitivityStudyCaseV2(Study="mass",Model="pointMass", ...
                Aero=true,LoadTransfer=false,Energy=true, ...
                PowertrainLayout="fourMotorAWD", ...
                TireModel="fittedCombinedSlip",IncludeDriverless=false, ...
                CoupleEnergy=false,CreatePlots=false);
            testCase.verifyEqual(config.model,'pointMass');
            testCase.verifyTrue(config.features.aero);
            testCase.verifyFalse(config.features.tireSlip);
        end

        function sensitivityV2CompletesRealBaselineCase(testCase)
            root=fileparts(fileparts(mfilename('fullpath')));
            addpath(fullfile(root,'config'));
            config=sensitivityStudyCaseV2(Study="mass",Model="pointMass", ...
                Aero=true,LoadTransfer=false,Energy=true, ...
                PowertrainLayout="fourMotorAWD", ...
                TireModel="fittedCombinedSlip",IncludeDriverless=false, ...
                CoupleEnergy=false,CreatePlots=false);
            config.parameters.values=config.parameters.baseline;
            config.events=config.events(strcmp({config.events.id}, ...
                'acceleration'));
            study=runSensitivityStudyV2(config);
            testCase.verifyEqual(numel(study.cases),1);
            testCase.verifyGreaterThan(study.eventTimes_s(1),0);
            testCase.verifyEqual(study.meta.v2Configuration.model, ...
                'pointMass');
        end

        function disabledEnergyIsAbsentFromEventModel(testCase)
            [model,effective]=lts.v2.buildDirectModel( ...
                Vehicle=FAUmaxTauV2(),Model="pointMass",Aero=true, ...
                LoadTransfer=false,Energy=false,YawInertia=false, ...
                ChassisTorsion=false);
            testCase.verifyFalse(isfield(model.vehicle,'energy'));
            testCase.verifyFalse(isfield(effective.vehicle,'energy'));
        end
    end
end
